#!/usr/bin/env python3
"""src/styles/tokens.json -> src/styles/tokens.css (CSS variables + Tailwind v4 @theme). Rerun after token changes."""
import json, sys, pathlib

here = pathlib.Path(__file__).resolve().parent.parent / "src" / "styles"
t = json.loads((here / "tokens.json").read_text())
c = t["color"]
light = {k: v for k, v in c.items() if isinstance(v, str)}
dark, bar = c["dark"], c["bar"]
assert set(light) == set(dark), "light and dark must define the same roles: %s" % (set(light) ^ set(dark))

def block(d, prefix=""):
    return "\n".join("  --c-%s%s: %s;" % (prefix, k, v) for k, v in d.items())

# Tailwind class names: text-fg, text-muted, border-input (avoids text-text and the --text-* font-size namespace)
ALIAS = {"text": "fg", "text-muted": "muted", "border-input": "input"}

out = ["/* Generated by scripts/gen_tokens.py from tokens.json. Do not edit by hand. */", "", ":root {",
       block(light), block(bar, "bar-")]
out += ["  --motion-%s: %s;" % (k, v) for k, v in t["motion"].items()]
out += ["  --sidebar: %spx;" % t["layout"]["sidebar"], "  --content-max: %spx;" % t["layout"]["content-max"],
        "  color-scheme: light;", "}", "",
        "/* theme=system follows macOS; theme=light|dark is set on <html data-theme> */",
        "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {", block(dark).replace("  --c-", "    --c-"),
        "    color-scheme: dark;", "  }", "}", ":root[data-theme=\"dark\"] {", block(dark), "  color-scheme: dark;", "}", "",
        "/* Tailwind v4: bg-surface, text-muted, border-input, rounded-md, shadow-pop, text-sm ... */", "@theme inline {"]
out += ["  --color-%s: var(--c-%s);" % (ALIAS.get(k, k), k) for k in light]
out += ["  --color-bar-%s: var(--c-bar-%s);" % (k, k) for k in bar]
out += ["  --font-sans: %s;" % t["font"]["sans"], "  --font-mono: %s;" % t["font"]["mono"]]
out += ["  --radius-%s: %spx;" % (k, v) for k, v in t["radius"].items()]
out += ["  --shadow-%s: %s;" % (k, v) for k, v in t["shadow"].items()]
for k, v in t["type"].items():
    out += ["  --text-%s: %spx;" % (k, v["size"]), "  --text-%s--line-height: %spx;" % (k, v["line"]),
            "  --text-%s--font-weight: %s;" % (k, v["weight"])]
out += ["  --spacing: 4px;", "}", ""]
(here / "tokens.css").write_text("\n".join(out))
print("wrote tokens.css")
